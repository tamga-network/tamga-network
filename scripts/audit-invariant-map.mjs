// Denetçi paketi (docs/audit/) için değişmez → test eşlemesi. INVARIANTS dosyasındaki her `DOC-ID/KOD` için testlerde atıf arar.
// Eşleşme türleri (sezgisel; denetçi için başlangıç noktası, kanıt değil):
//   direct  — test dosyası `DOC-ID/KOD` ya da `DOC-ID KOD` yazıyor
//   scoped  — test dosyası kısa kodu sözcük olarak VE aynı belgenin kimliğini (ya da ADR numarasını) yazıyor
//   unique  — kısa kod bütün değişmezlerde tekil ve test dosyası onu sözcük olarak yazıyor
// Kullanım:
//   node scripts/audit-invariant-map.mjs            → docs/audit/invariants.md (public kapsam: .publicoverride/INVARIANTS.md,
//                                                     kontratlar hariç)
//   node scripts/audit-invariant-map.mjs --contracts → docs/audit/contracts-invariants.md (SPEC-BC-*, ADR-0051…0055; kontrat
//                                                     testleri dahil — .publicignore'da, public depoya girmez)
//   --check: dosyayı yazmaz, güncel değilse çıkış 1
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(fileURLToPath(import.meta.url), "..", "..");
const contracts = process.argv.includes("--contracts");
const check = process.argv.includes("--check");
const src = contracts
  ? "INVARIANTS.md"
  : existsSync(join(repo, ".publicoverride/INVARIANTS.md"))
    ? ".publicoverride/INVARIANTS.md"
    : "INVARIANTS.md";
const out = join(repo, "docs/audit", contracts ? "contracts-invariants.md" : "invariants.md");
const CONTRACT_DOCS = /^(SPEC-BC-\d+|ADR-005[1-5])$/;

// ---- değişmezler
const rows = [];
let doc = null;
let title = "";
for (const line of readFileSync(join(repo, src), "utf8").split(/\r?\n/)) {
  const h = /^## ([A-Z][A-Z0-9-]+)\s*$/.exec(line);
  if (h) {
    doc = h[1];
    title = "";
    continue;
  }
  const t = /^\*"(.+)"\*$/.exec(line);
  if (t && doc) title = t[1];
  const m = /^\| `([A-Z][A-Z0-9-]+)\/([A-Za-z0-9.-]+)` \| (.*) \|\s*$/.exec(line);
  if (m) rows.push({ doc: m[1], code: m[2], title, text: m[3] });
}
const selected = rows.filter((r) => (contracts ? CONTRACT_DOCS.test(r.doc) : true));
const codeCount = new Map();
for (const r of rows) codeCount.set(r.code, (codeCount.get(r.code) ?? 0) + 1);

// ---- testler
function walk(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const n of readdirSync(dir)) {
    if (n === "node_modules" || n === "artifacts" || n === "cache" || n.startsWith(".")) continue;
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (/\.test\.ts$/.test(n)) acc.push(p);
  }
  return acc;
}
const roots = ["packages", "apps", "conformance", "examples", "scripts", ...(contracts ? ["contracts/test"] : [])];
const tests = roots
  .flatMap((r) => walk(join(repo, r)))
  .map((p) => ({ path: relative(repo, p).split(sep).join("/"), text: readFileSync(p, "utf8") }))
  .filter((t) => !t.path.startsWith("scripts/private-names"))
  .sort((a, b) => a.path.localeCompare(b.path));

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const adrNum = (d) => (/^ADR-(\d+)$/.exec(d) ? `ADR-${d.slice(4)}` : d);
function match(r) {
  const word = new RegExp(`(?<![A-Za-z0-9])${esc(r.code)}(?![A-Za-z0-9])`);
  const direct = new RegExp(`${esc(r.doc)}[/ ]${esc(r.code)}(?![A-Za-z0-9])`);
  const hits = [];
  for (const t of tests) {
    if (direct.test(t.text)) hits.push({ path: t.path, kind: "direct" });
    else if (word.test(t.text) && t.text.includes(adrNum(r.doc))) hits.push({ path: t.path, kind: "scoped" });
    else if (codeCount.get(r.code) === 1 && r.code.length >= 3 && word.test(t.text))
      hits.push({ path: t.path, kind: "unique" });
  }
  const rank = { direct: 0, scoped: 1, unique: 2 };
  hits.sort((a, b) => rank[a.kind] - rank[b.kind] || a.path.localeCompare(b.path));
  return hits;
}

// ---- çıktı
const byDoc = new Map();
for (const r of selected) {
  if (!byDoc.has(r.doc)) byDoc.set(r.doc, []);
  byDoc.get(r.doc).push({ ...r, hits: match(r) });
}
const all = [...byDoc.values()].flat();
const covered = all.filter((r) => r.hits.length).length;
const directN = all.filter((r) => r.hits.some((h) => h.kind === "direct")).length;
const cell = (s) => s.replace(/\|/g, "\\|").replace(/\[\[([^\]]+)\]\]/g, "$1");
const short = (s) => {
  const c = cell(s);
  return c.length > 140 ? c.slice(0, 137).trimEnd() + "…" : c;
};

const lines = [
  `# ${contracts ? "Contract invariant catalogue" : "Invariant catalogue"} → tests`,
  "",
  `Generated by \`node scripts/audit-invariant-map.mjs${contracts ? " --contracts" : ""}\` from \`${src}\` — do not edit by hand.`,
  "Invariant texts are the project's binding rules (Turkish in the source; quoted here truncated). The test column is a",
  "**heuristic** search of the test suites for the invariant code, meant as a starting point for the reviewer, not as proof:",
  "",
  "- **direct** — the test names the invariant as `DOC-ID/CODE` (strongest).",
  "- **scoped** — the test uses the short code and mentions the same document.",
  "- **unique** — the short code is unique across all invariants and the test uses it.",
  "",
  "Rows without a test are either enforced by construction (types, schemas, data files, publication scripts), covered by tests",
  "that do not cite the code, process rules (governance, documentation), or genuinely untested. Reviewers should treat",
  "untested rows in the parsing, signature, status and trust-list areas as priority questions.",
  "",
  `**Summary:** ${all.length} invariants in ${byDoc.size} documents · ${covered} with at least one test reference ` +
    `(${Math.round((covered / Math.max(all.length, 1)) * 100)}%) · ${directN} with a direct reference.`,
  "",
];
for (const [d, rs] of byDoc) {
  lines.push(
    `## ${d}${rs[0].title ? ` — ${cell(rs[0].title)}` : ""}`,
    "",
    "| Code | Rule (truncated) | Tests | Match |",
    "|---|---|---|---|",
  );
  for (const r of rs) {
    const top = r.hits.slice(0, 3);
    const more = r.hits.length > 3 ? ` +${r.hits.length - 3}` : "";
    lines.push(
      `| \`${r.code}\` | ${short(r.text)} | ${top.map((h) => `\`${h.path}\``).join("<br>") || "—"}${more} | ${top[0]?.kind ?? "none"} |`,
    );
  }
  lines.push("");
}
const text = lines.join("\n");
if (check) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (cur !== text) {
    console.error(`audit-invariant-map: ${relative(repo, out)} is stale — run the script`);
    process.exit(1);
  }
  console.log(`audit-invariant-map: ${relative(repo, out)} up to date`);
} else {
  writeFileSync(out, text);
  console.log(
    `audit-invariant-map: ${relative(repo, out)} — ${all.length} invariants, ${covered} with tests, ${directN} direct`,
  );
}
